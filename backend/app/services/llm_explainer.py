import logging
import requests
from typing import Dict, Any, Optional
from ..config import settings

logger = logging.getLogger(__name__)

def generate_deterministic_explanation(computed_results: Dict[str, Any]) -> str:
    """
    Fallback deterministic explanation generated by backend rules without calling external LLM.
    Guarantees zero halluncinations and instant response.
    """
    comp = computed_results.get("base_component", {})
    pn = comp.get("part_number", "Component")
    mfr = comp.get("manufacturer", "Unknown")
    crit = comp.get("user_criticality", "MEDIUM")
    viable_count = computed_results.get("candidates_count", 0)
    top_cand = (computed_results.get("candidates") or [None])[0]

    explanation = f"Technical Assessment for {pn} ({mfr}):\n"
    explanation += f"- Operational Criticality: {crit}.\n"
    
    if viable_count > 0 and top_cand:
        alt_pn = top_cand.get("part_number")
        alt_mfr = top_cand.get("manufacturer")
        alt_origin = top_cand.get("origin_label")
        score = top_cand.get("heuristic_score")
        matches = top_cand.get("matches_count")
        unknowns = top_cand.get("unknowns_count")
        
        explanation += (
            f"- Recommended Alternative: {alt_pn} manufactured by {alt_mfr} ({alt_origin}).\n"
            f"- Compatibility Confidence: Heuristic score of {score}% based on {matches} matching verified specifications.\n"
            f"- Packaging & Effort: {top_cand.get('redesign_note')}.\n"
        )
        if unknowns > 0:
            explanation += f"- Engineering Advisory: {unknowns} parameter(s) remain UNKNOWN in source records. Laboratory bench testing is required.\n"
    else:
        explanation += "- Alternative Sourcing: No verified suitable replacement was found in the current catalogue. Single-source supply mitigation is advised.\n"

    explanation += "\nNotice: This explanation is algorithmically generated based on deterministic rule constraints."
    return explanation


def explain_alternative_result(computed_results: Dict[str, Any]) -> Dict[str, Any]:
    """
    Explains the computed results. If ENABLE_LLM_EXPLAINER is False or unconfigured,
    returns deterministic explanation immediately.
    """
    if not settings.ENABLE_LLM_EXPLAINER:
        return {
            "source": "DETERMINISTIC_RULES",
            "provider": "Built-in Rule Engine (LLM Disabled)",
            "explanation": generate_deterministic_explanation(computed_results)
        }

    # If LLM enabled, call Ollama or configured provider
    try:
        prompt = (
            "You are an electronic component engineering assistant. Explain the following computed compatibility result in 3 clear sentences. "
            "STRICT RULES: Do NOT invent specifications, country of origin, or availability. Use ONLY provided facts. "
            "Explicitly mention any UNKNOWN fields.\n\n"
            f"Data: {computed_results}"
        )

        if settings.LLM_PROVIDER == "ollama":
            url = f"{settings.LLM_API_BASE}/api/generate"
            payload = {
                "model": settings.LLM_MODEL,
                "prompt": prompt,
                "stream": False
            }
            resp = requests.post(url, json=payload, timeout=5)
            if resp.status_code == 200:
                text = resp.json().get("response", "").strip()
                return {
                    "source": "LLM_EXPLAINER",
                    "provider": f"Ollama ({settings.LLM_MODEL})",
                    "explanation": text
                }
    except Exception as e:
        logger.warning(f"LLM Explainer failed, falling back to deterministic: {e}")

    return {
        "source": "DETERMINISTIC_FALLBACK",
        "provider": "Built-in Rule Engine (LLM Fallback)",
        "explanation": generate_deterministic_explanation(computed_results)
    }
